"""
Report generation for evaluation results.

Generates markdown reports suitable for client demonstrations.
"""

from datetime import datetime
from typing import Optional

from coalition_eval.core.results import EvalRun


def generate_markdown_report(
    run: EvalRun,
    title: Optional[str] = None,
    include_responses: bool = False,
) -> str:
    """
    Generate a markdown report from an evaluation run.

    Args:
        run: Evaluation run with results
        title: Optional custom title
        include_responses: Include full response text

    Returns:
        Markdown formatted report
    """
    title = title or f"Evaluation Report: {run.model}"

    lines = [
        f"# {title}",
        "",
        f"**Run ID**: {run.run_id}",
        f"**Model**: {run.model}",
        f"**Tier**: {run.tier}",
        f"**Date**: {run.started_at[:10]}",
        "",
        "## System Information",
        "",
        f"- **Host**: {run.system_info.hostname}",
        f"- **CPU**: {run.system_info.cpu}",
        f"- **RAM**: {run.system_info.ram_gb} GB",
        f"- **GPUs**: {', '.join(run.system_info.gpus) or 'None'}",
        "",
        "## Summary",
        "",
        f"| Metric | Value |",
        f"|--------|-------|",
        f"| Pass Rate | {run.pass_rate:.1%} |",
        f"| Average Score | {run.avg_score:.2f} |",
        f"| Average Latency | {run.avg_latency_ms:.0f}ms |",
        f"| Total Tokens | {run.total_tokens:,} |",
        "",
        "## Results by Test",
        "",
        "| Test | Status | Score | Latency |",
        "|------|--------|-------|---------|",
    ]

    for result in run.results:
        status = "\u2713" if result.passed else "\u2717"
        lines.append(
            f"| {result.test_name} | {status} | {result.score:.2f} | {result.latency_ms:.0f}ms |"
        )

    lines.append("")

    # Error breakdown
    errors = run.error_breakdown
    non_none = {k: v for k, v in errors.items() if k != "none"}
    if non_none:
        lines.extend([
            "## Error Breakdown",
            "",
            "| Category | Count |",
            "|----------|-------|",
        ])
        for cat, count in sorted(non_none.items(), key=lambda x: -x[1]):
            lines.append(f"| {cat} | {count} |")
        lines.append("")

    # Detailed results
    if include_responses:
        lines.extend([
            "## Detailed Results",
            "",
        ])
        for result in run.results:
            status = "PASS" if result.passed else "FAIL"
            lines.extend([
                f"### {result.test_name} ({status})",
                "",
                f"**Score**: {result.score:.2f}",
                f"**Latency**: {result.latency_ms:.0f}ms",
                f"**Tokens**: {result.tokens_used}",
                "",
                "**Response**:",
                "```",
                result.response_text[:500] + ("..." if len(result.response_text) > 500 else ""),
                "```",
                "",
            ])

    # Footer
    lines.extend([
        "---",
        "",
        f"*Generated by Coalition Eval Suite at {datetime.now().isoformat()}*",
    ])

    return "\n".join(lines)


def generate_comparison_report(
    run_a: EvalRun,
    run_b: EvalRun,
    title: Optional[str] = None,
) -> str:
    """
    Generate a comparison report between two evaluation runs.

    Args:
        run_a: First (baseline) run
        run_b: Second (comparison) run
        title: Optional custom title

    Returns:
        Markdown formatted comparison report
    """
    from coalition_eval.metrics.scoring import compare_runs

    comparison = compare_runs(run_a, run_b)
    title = title or f"Model Comparison: {run_a.model} vs {run_b.model}"

    lines = [
        f"# {title}",
        "",
        f"**Date**: {datetime.now().strftime('%Y-%m-%d')}",
        "",
        "## Summary",
        "",
        "| Metric | {run_a.model} | {run_b.model} | Delta |",
        "|--------|---------------|---------------|-------|",
        f"| Pass Rate | {run_a.pass_rate:.1%} | {run_b.pass_rate:.1%} | {comparison['score_delta']:+.1%} |",
        f"| Avg Score | {run_a.avg_score:.2f} | {run_b.avg_score:.2f} | {comparison['score_delta']:+.2f} |",
        f"| Avg Latency | {run_a.avg_latency_ms:.0f}ms | {run_b.avg_latency_ms:.0f}ms | {comparison['latency_delta_ms']:+.0f}ms |",
        "",
    ]

    if comparison["improvements"]:
        lines.extend([
            "## Improvements",
            "",
        ])
        for imp in comparison["improvements"]:
            lines.append(f"- **{imp['test']}**: {imp['from']:.2f} \u2192 {imp['to']:.2f} ({imp['delta']:+.2f})")
        lines.append("")

    if comparison["regressions"]:
        lines.extend([
            "## Regressions",
            "",
        ])
        for reg in comparison["regressions"]:
            lines.append(f"- **{reg['test']}**: {reg['from']:.2f} \u2192 {reg['to']:.2f} ({reg['delta']:+.2f})")
        lines.append("")

    if comparison["unchanged"]:
        lines.extend([
            f"## Unchanged ({len(comparison['unchanged'])} tests)",
            "",
            ", ".join(comparison["unchanged"]),
            "",
        ])

    lines.extend([
        "---",
        "",
        f"*Generated by Coalition Eval Suite at {datetime.now().isoformat()}*",
    ])

    return "\n".join(lines)
