def generate_executive_summary(run: EvalRun, audience: str = "technical") -> str:
    """
    Generate an executive summary for different audiences.

    Args:
        run: Evaluation run with results
        audience: "technical", "investor", or "general"

    Returns:
        Markdown formatted executive summary
    """
    # Calculate key metrics
    passed = sum(1 for r in run.results if r.passed)
    total = len(run.results)

    # Determine recommendation
    if run.pass_rate >= 0.9:
        recommendation = "RECOMMENDED for production deployment"
        status = "excellent"
    elif run.pass_rate >= 0.7:
        recommendation = "SUITABLE for production with monitoring"
        status = "good"
    elif run.pass_rate >= 0.5:
        recommendation = "REQUIRES improvement before production"
        status = "needs_work"
    else:
        recommendation = "NOT RECOMMENDED for production use"
        status = "poor"

    # Group results by tier
    tier_map = {
        1: ["basic_reasoning", "instruction_following", "tool_format", "json_output", "multi_turn"],
        2: ["tool_selection", "multi_step_planning", "tool_chaining", "error_recovery", "context_management"],
        3: ["prompt_injection", "refusal_handling", "consistency", "edge_cases"],
        4: ["skill_routing", "efe_compliance", "verifier_pass_rate", "bdi_alignment"],
    }

    tier_names = {
        1: "Core Capabilities",
        2: "Orchestration",
        3: "Robustness & Safety",
        4: "Kintsugi Integration",
    }

    if audience == "investor":
        lines = [
            f"# Model Evaluation: {run.model}",
            "",
            "## Bottom Line",
            "",
            f"**{recommendation}**",
            "",
            f"The {run.model} model achieved a **{run.pass_rate:.0%} pass rate** across {total} evaluation criteria. "
            f"Average response latency is **{run.avg_latency_ms:.0f}ms**, suitable for interactive applications.",
            "",
            "## Key Metrics",
            "",
            "| Metric | Value | Implication |",
            "|--------|-------|-------------|",
            f"| Pass Rate | {run.pass_rate:.0%} | {'Production-ready' if run.pass_rate >= 0.7 else 'Needs improvement'} |",
            f"| Avg Latency | {run.avg_latency_ms:.0f}ms | {'Interactive' if run.avg_latency_ms < 2000 else 'Batch processing'} |",
            f"| Token Usage | {run.total_tokens:,} | Cost factor for API pricing |",
            "",
            "## Capability Summary",
            "",
        ]

        for tier, tests in tier_map.items():
            tier_results = [r for r in run.results if r.test_name in tests]
            if tier_results:
                tier_pass = sum(1 for r in tier_results if r.passed) / len(tier_results)
                icon = "✓" if tier_pass >= 0.7 else "⚠" if tier_pass >= 0.5 else "✗"
                lines.append(f"- **{tier_names[tier]}**: {icon} {tier_pass:.0%}")

        lines.extend([
            "",
            "## Cost Considerations",
            "",
            f"- **Total tokens used**: {run.total_tokens:,}",
            f"- **Estimated cost per 1000 evals**: ${run.total_tokens * 0.000003 * 1000:.2f} (at $3/1M tokens)",
            "",
        ])

    elif audience == "general":
        lines = [
            f"# How Did {run.model} Perform?",
            "",
            f"We tested this AI model with {total} different challenges. Here's what we found:",
            "",
            f"## Overall Score: {run.pass_rate:.0%}",
            "",
            f"The model passed {passed} out of {total} tests.",
            "",
            "### What it's good at:",
            "",
        ]

        # Find strengths
        high_scores = [r for r in run.results if r.score >= 0.8]
        for r in high_scores[:3]:
            lines.append(f"- {r.test_name.replace('_', ' ').title()}")

        lines.append("")
        lines.append("### Areas for improvement:")
        lines.append("")

        # Find weaknesses
        low_scores = [r for r in run.results if r.score < 0.5]
        for r in low_scores[:3]:
            lines.append(f"- {r.test_name.replace('_', ' ').title()}")

        lines.extend([
            "",
            f"## Speed: {run.avg_latency_ms:.0f}ms average",
            "",
            "This means responses typically come back in under a second.",
        ])

    else:  # technical
        lines = [
            f"# Technical Evaluation: {run.model}",
            "",
            f"**Status**: {recommendation}",
            "",
            "## Test Configuration",
            "",
            f"- **Tier**: {run.tier}",
            f"- **Tests**: {total}",
            f"- **System**: {run.system_info.hostname} ({run.system_info.cpu}, {run.system_info.ram_gb}GB RAM)",
            f"- **GPUs**: {', '.join(run.system_info.gpus) or 'None'}",
            "",
            "## Results by Category",
            "",
        ]

        for tier, tests in tier_map.items():
            tier_results = [r for r in run.results if r.test_name in tests]
            if tier_results:
                tier_pass = sum(1 for r in tier_results if r.passed)
                tier_total = len(tier_results)
                tier_avg = sum(r.score for r in tier_results) / tier_total
                tier_lat = sum(r.latency_ms for r in tier_results) / tier_total

                lines.extend([
                    f"### Tier {tier}: {tier_names[tier]}",
                    "",
                    f"- Pass: {tier_pass}/{tier_total} ({tier_pass/tier_total:.0%})",
                    f"- Avg Score: {tier_avg:.2f}",
                    f"- Avg Latency: {tier_lat:.0f}ms",
                    "",
                ])

        # Error analysis
        errors = run.error_breakdown
        non_none = {k: v for k, v in errors.items() if k != "none" and v > 0}
        if non_none:
            lines.extend([
                "## Error Analysis",
                "",
            ])
            for cat, count in sorted(non_none.items(), key=lambda x: -x[1]):
                lines.append(f"- **{cat}**: {count} occurrences")
            lines.append("")

    # Common footer
    lines.extend([
        "---",
        "",
        f"*Report generated {datetime.now().strftime('%Y-%m-%d %H:%M')} by Coalition Eval Suite*",
    ])

    return "\n".join(lines)
